def _root_setup(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(_udev.os, "geteuid", lambda: 0)
    monkeypatch.setattr(_udev, "_write_atomic", lambda path, content: None)
    monkeypatch.setattr(_udev.subprocess, "run", lambda *a, **k: None)
    monkeypatch.setattr(_udev, "_reload_udev", lambda: 0)


def test_setup_retires_trccs_every_user_rule_file(
    dirs, monkeypatch: pytest.MonkeyPatch,
) -> None:
    """The old 99- file granted every user and udev reads it after the new
    70- one, so its mode would win.  TRCC's own goes; an admin's stays.
    MUTATION CHECK: drop ``_retire_legacy_rules`` from ``install``."""
    etc, _lib = dirs
    _root_setup(monkeypatch)
    legacy = etc / _udev.LEGACY_RULES_NAME
    legacy.write_text("# Thermalright TRCC devices — generated by `trcc system "
                      "setup` (and packaged)\nMODE=\"0666\"\n", encoding="utf-8")
    assert _udev.install() == 0
    assert not legacy.exists()
    legacy.write_text("# my own rule\n", encoding="utf-8")
    assert _udev.install() == 0
    assert legacy.read_text(encoding="utf-8") == "# my own rule\n"


class _System:
    """groupadd / usermod / the group database, recorded -- never the host's."""

    def __init__(self, monkeypatch: pytest.MonkeyPatch, members: list[str] | None) -> None:
        import grp
        import types

        self.ran: list[list[str]] = []

        def getgrnam(name: str) -> object:
            if members is None:
                raise KeyError(name)
            return types.SimpleNamespace(gr_mem=members)

        monkeypatch.setattr(grp, "getgrnam", getgrnam)
        monkeypatch.setattr(_udev.shutil, "which", lambda name: f"/usr/sbin/{name}")
        monkeypatch.setattr(_udev.subprocess, "run", lambda cmd, **k: (
            self.ran.append(cmd) or types.SimpleNamespace(returncode=0)))


def test_the_group_is_made_and_the_user_joins_it(monkeypatch: pytest.MonkeyPatch) -> None:
    """MUTATION CHECK: skip the usermod when the group was just made."""
    system = _System(monkeypatch, members=None)
    _udev._join_device_group("alice")
    assert system.ran == [["groupadd", "--system", "trcc"],
                          ["usermod", "-aG", "trcc", "alice"]]


def test_a_member_is_left_as_is(monkeypatch: pytest.MonkeyPatch) -> None:
    system = _System(monkeypatch, members=["alice"])
    _udev._join_device_group("alice")
    _udev._join_device_group(None)              # a root login: nobody to add
    assert system.ran == []


@pytest.mark.parametrize("env, user", [
    ({"SUDO_USER": "alice"}, "alice"),
    ({}, None),
], ids=["sudo", "root-login"])
def test_setup_adds_the_user_it_runs_for(
        monkeypatch: pytest.MonkeyPatch, env: dict[str, str], user: str | None) -> None:
    for key in ("SUDO_USER", "PKEXEC_UID"):
        monkeypatch.delenv(key, raising=False)
    for key, value in env.items():
        monkeypatch.setenv(key, value)
    assert _udev._invoking_user() == user
